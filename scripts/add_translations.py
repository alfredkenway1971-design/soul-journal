LANGS = ["en", "fr", "es", "ar", "zh", "ja", "sw", "de"]

def insert_keys(path):
    with open(path) as f:
        content = f.read()
    for lang in LANGS:
        keys = NEW_KEYS[lang]
        if not keys:
            continue
        # Find the language block: "  lang: {" ... "  },"
        marker = f"  {lang}: {{"
        idx = content.index(marker)
        # Find the closing "  }," of this block (next occurrence after the opening brace)
        close_idx = content.index("  },", idx)
        block = content[idx:close_idx]
        # Build insertion: after the last key in block
        lines = []
        for k, v in keys.items():
            lines.append(f'    "{k}": "{v}",')
        insert_text = "\n" + "\n".join(lines)
        # Insert before the closing "  },"
        new_block = block.rstrip() + insert_text + "\n"
        content = content[:idx] + new_block + content[close_idx:]
    with open(path, "w") as f:
        f.write(content)
    print("Inserted keys into", path)

